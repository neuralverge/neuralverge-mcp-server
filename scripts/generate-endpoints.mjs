#!/usr/bin/env node
// Generates src/endpoints.generated.ts from the NeuralVerge OpenAPI spec.
// Usage: node scripts/generate-endpoints.mjs [spec-path-or-url]   (default: https://docs.neuralverge.ai/openapi.json)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const source = process.argv[2] ?? "https://docs.neuralverge.ai/openapi.json";
const raw = /^https?:\/\//.test(source)
  ? await (await fetch(source)).text()
  : readFileSync(source, "utf8");
const spec = JSON.parse(raw);

// Keep only what is needed to build input validation (drop examples/responses).
function clean(schema) {
  if (!schema || typeof schema !== "object") return schema;
  const out = {};
  for (const key of ["type", "description", "format", "enum", "default", "minimum", "maximum", "required"]) {
    if (schema[key] !== undefined) out[key] = schema[key];
  }
  if (schema.properties) {
    out.properties = Object.fromEntries(
      Object.entries(schema.properties).map(([k, v]) => [k, clean(v)]),
    );
  }
  if (schema.items) out.items = clean(schema.items);
  return out;
}

// The hosted MCP server (docs.neuralverge.ai/mcp-server) names six review tools differently
// from their REST paths; use the MCP names so tool names match the official MCP server.
const NAME_OVERRIDES = {
  run_capterra_products: "run_capterra_product",
  run_capterra_categories_products: "run_capterra_category_products",
  run_gartner_products: "run_gartner_product",
  run_gartner_vendors: "run_gartner_vendor",
  run_gartner_markets: "run_gartner_market",
  run_gartner_markets_products: "run_gartner_market_products",
};

const endpoints = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!["get", "post"].includes(method)) continue;
    const pathName = path.split("/").pop().replace(/-/g, "_");
    const name = NAME_OVERRIDES[pathName] ?? pathName;
    let schema;
    if (method === "get") {
      const params = op.parameters ?? [];
      schema = {
        type: "object",
        properties: Object.fromEntries(
          params.map((p) => [p.name, clean({ ...p.schema, description: p.description ?? p.schema?.description })]),
        ),
        required: params.filter((p) => p.required).map((p) => p.name),
      };
    } else {
      schema = clean(op.requestBody?.content?.["application/json"]?.schema) ?? { type: "object", properties: {} };
    }
    const desc = [op.description ?? op.summary, `[${(op.tags ?? []).join(", ")}]`].filter(Boolean).join(" ");
    endpoints.push({ name, method: method.toUpperCase(), path, tag: (op.tags ?? ["Other"])[0], description: desc, schema });
  }
}

const names = new Set();
for (const e of endpoints) {
  if (names.has(e.name)) throw new Error(`Duplicate tool name: ${e.name}`);
  names.add(e.name);
}

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, "..", "src", "endpoints.generated.ts");
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/generate-endpoints.mjs from https://docs.neuralverge.ai/openapi.json — do not edit by hand.\n` +
    `import type { EndpointDef } from "./endpoint-types.js";\n\n` +
    `export const endpoints: EndpointDef[] = ${JSON.stringify(endpoints, null, 1)};\n`,
);
// Human-readable catalog of all tools.
const byTag = new Map();
for (const e of endpoints) {
  if (!byTag.has(e.tag)) byTag.set(e.tag, []);
  byTag.get(e.tag).push(e);
}
const oneLine = (t) => String(t ?? "").replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
const paramList = (schema) => {
  const req = new Set(schema.required ?? []);
  return Object.keys(schema.properties ?? {})
    .map((k) => (req.has(k) ? `\`${k}\`*` : `\`${k}\``))
    .join(", ");
};
let md = `# Tool catalog\n\n_Auto-generated by \`npm run generate\` from the NeuralVerge OpenAPI spec (https://docs.neuralverge.ai/openapi.json). ${endpoints.length} tools. Required parameters are marked with *._\n\n`;
md += `| Category | Tools |\n| --- | --- |\n${[...byTag].map(([t, l]) => `| ${t} | ${l.length} |`).join("\n")}\n\n`;
for (const [tag, list] of byTag) {
  md += `## ${tag} (${list.length})\n\n| Tool | Endpoint | Parameters | Description |\n| --- | --- | --- | --- |\n`;
  for (const e of list) {
    md += `| \`${e.name}\` | \`${e.method} ${e.path}\` | ${paramList(e.schema)} | ${oneLine(e.description)} |\n`;
  }
  md += "\n";
}
mkdirSync(join(here, "..", "docs"), { recursive: true });
writeFileSync(join(here, "..", "docs", "TOOLS.md"), md);

console.log(`Generated ${endpoints.length} endpoints -> ${outFile}`);
